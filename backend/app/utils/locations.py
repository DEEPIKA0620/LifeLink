def get_location_coords(city_name: str, locality_name: str = None):
    """Returns (lat, lon) for given city and optional locality, or None"""
    if not city_name:
        return None
    city_match = None
    for c_name, c_data in SUPPORTED_LOCATIONS.items():
        if c_name.lower() == city_name.lower() or city_name.lower() in c_name.lower():
            city_match = c_data
            break
    if not city_match:
        return None

    if locality_name:
        for l_name, l_data in city_match["localities"].items():
            if l_name.lower() == locality_name.lower() or locality_name.lower() in l_name.lower():
                return l_data["lat"], l_data["lon"]

    return city_match["center"]["lat"], city_match["center"]["lon"]
